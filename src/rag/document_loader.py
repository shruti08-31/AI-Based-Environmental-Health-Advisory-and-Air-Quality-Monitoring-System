@dataclass(frozen=True)
class DocumentChunk:
    chunk_id: str
    doc_id: str
    title: str
    source: str
    chunk_index: int
    text: str


def ensure_curated_knowledge_base(kb_dir: Path | str | None = None) -> Path:
    target_dir = Path(kb_dir) if kb_dir is not None else DEFAULT_KB_DIR
    target_dir.mkdir(parents=True, exist_ok=True)
    for filename, meta in CURATED_KNOWLEDGE_DOCS.items():
        fpath = target_dir / filename
        if not fpath.exists():
            body = (
                f"# {meta['title']}\n"
                f"Source: {meta['source']}\n\n"
                f"{meta['content']}\n"
            )
            fpath.write_text(body, encoding="utf-8")
    return target_dir


def clean_text(raw_text: str) -> str:
    cleaned = raw_text.replace("\r\n", "\n").replace("\r", "\n")
    cleaned = re.sub(r"[ \t]+", " ", cleaned)
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)
    return cleaned.strip()


def chunk_text(text: str, chunk_size: int = 420, overlap: int = 80) -> list[str]:
    normalized = clean_text(text)
    if not normalized:
        return []
    if len(normalized) <= chunk_size:
        return [normalized]

    chunks: list[str] = []
    step = max(1, chunk_size - overlap)
    start = 0
    while start < len(normalized):
        end = min(len(normalized), start + chunk_size)
        if end < len(normalized):
            # Prefer breaking on a sentence or whitespace boundary
            boundary = normalized.rfind(". ", start + int(chunk_size * 0.5), end)
            if boundary == -1:
                boundary = normalized.rfind(" ", start + int(chunk_size * 0.5), end)
            if boundary > start:
                end = boundary + 1
        piece = normalized[start:end].strip()
        if piece:
            chunks.append(piece)
        if end >= len(normalized):
            break
        start = max(start + 1, end - overlap)
    return chunks


def load_and_chunk_documents(
    kb_dir: Path | str | None = None,
    chunk_size: int = 420,
    overlap: int = 80,
) -> list[DocumentChunk]:
    directory = ensure_curated_knowledge_base(kb_dir)
    files = sorted(
        p for p in directory.iterdir() if p.is_file() and p.suffix.lower() in (".md", ".txt")
    )

    all_chunks: list[DocumentChunk] = []
    for fpath in files:
        raw = fpath.read_text(encoding="utf-8", errors="ignore")
        lines = [ln.strip() for ln in raw.splitlines() if ln.strip()]
        title = fpath.stem.replace("_", " ").title()
        source = f"Knowledge Base ({fpath.name})"
        body_lines: list[str] = []

        for ln in lines:
            if ln.startswith("# "):
                title = ln[2:].strip()
            elif ln.lower().startswith("source:"):
                source = ln.split(":", 1)[1].strip()
            else:
                body_lines.append(ln)

        extracted_body = clean_text(" ".join(body_lines))
        pieces = chunk_text(extracted_body, chunk_size=chunk_size, overlap=overlap)
        for idx, piece in enumerate(pieces):
            all_chunks.append(
                DocumentChunk(
                    chunk_id=f"{fpath.stem}::chunk_{idx}",
                    doc_id=fpath.name,
                    title=title,
                    source=source,
                    chunk_index=idx,
                    text=piece,
                )
            )
    return all_chunks